def _style_profile(style: str) -> dict:
    """取某风格完整画像（默认通用平衡）。"""
    return STYLE_PROFILE.get(style, STYLE_PROFILE["通用平衡"])


def _style_profile_text(style: str) -> str:
    """把画像渲染成可直接注入系统 prompt 的文字（chat 与 report 共用）。"""
    p = _style_profile(style)
    lines = [
        f"【必须严格遵守的沟通风格：{style}】",
        f"· 声音定位：{p['voice_one_liner']}",
        f"· 语气：{' / '.join(p['tone'])}",
        f"· 句式：{p['sentence']}",
        f"· 格式：",
        *[f"   - {f}" for f in p['format']],
        f"· 开篇：{p['opening']}",
        f"· 长度：{p['length']}",
        f"· 用词：{ '、'.join(p['vocabulary']) }",
        f"· 允许：{p['exclusive']}",
        f"· 禁用：",
        *[f"   - {x}" for x in p['forbidden']],
        "",
        "（重要：以上规则在每个模块、每条建议、每个示例里都要体现——换风格不是换形容词，"
        "是换整篇报告的句子构造、句长分布、表格/列表比例与开篇位置。）",
    ]
    return "\n".join(lines)


def _style_note(style: str) -> str:
    """短描述，向后兼容旧调用方；新代码统一用 _style_profile / _style_profile_text。"""
    return STYLE_NOTE.get(style, STYLE_NOTE["通用平衡"])

