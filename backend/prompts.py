def build_report_user_prompt(params: dict, kb_context: str = "") -> str:
    mode = params.get("mode", "deep")
    job = params.get("job", "目标岗位")
    job_desc = (params.get("jobDesc") or "").strip()
    stage = params.get("stage", "中级（3-5年）")
    style = params.get("style", "通用平衡")
    modules = params.get("modules") or []

    is_fast = (mode == "fast")
    mode_cn = _mode_cn(mode)
    style_note = _style_note(style)
    modules_cn = "、".join(modules) if modules else "全部 6 大模块"

    lines = [
        f"【目标转型方向】{job}",
        f"【生成模式】{mode_cn}",
        f"【职业阶段】{stage}",
        f"【沟通风格】{style}（{style_note}）",
        f"【本次需覆盖模块】{modules_cn}",
    ]
    if is_fast:
        lines.append(
            "【快速模式强制规范】信息不足时可合理推断填充并标注"
            "[基于有限信息推断，建议补充]；优先输出简历重写与行动建议、精简理论篇幅；"
            "在 parse 模块首张卡片开头固定加："
            "⚡ 快速分析模式——基于你提供的信息直接出结果，如需更精准分析可以补充更多细节；"
            "并在 tips 末张卡片末尾加：如需更精准的分析，可以补充更多经历细节，我会为你重新生成。"
        )
    if job_desc:
        src_label = "用户补充的经历描述" if not is_fast else "用户粘贴的原始简历文本（已抽取核心经历）"
        lines.append(f"\n【{src_label}】\n{job_desc}")
    else:
        # 注入差异化种子，让多次生成、缺 jobDesc 时也给出多样化结果
        import os
        seed_n = int.from_bytes(os.urandom(2), "big") % 1000
        lines.append(
            f"\n（用户未填写经历文本，请基于目标岗位「{job}」和阶段「{stage}」做一次"
            f"**强假设性**的诊断——给出三段『假设你是这类典型候选人』的样例描述，"
            f"并在句子里明确标注【假设】让读者知道这是推断；不要空泛套话。"
            f"本次随机种子 #{seed_n}，请基于这个种子选择切入角度，"
            f"避免给出与之前完全相同的措辞结构。）"
        )

    if kb_context:
        lines.append("\n【参考能力模型（来自知识库，仅做校准依据）】\n" + kb_context)

    lines.append(
        f"\n请严格按系统设定的 6 大模块输出，使用上文指定的 JSON 结构。"
        f"\n（额外要求：本次回答尽量多用具象数字、具体项目名，避免『建议 / 可以 / 通常』开头；"
        f"标题必须为本次内容定制，禁止『核心经历结构化拆解』『能力迁移建议』类通用标题。）"
    )
    return "\n".join(lines)


