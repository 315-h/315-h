def template_rewrite(params: dict) -> dict:
    action = params.get("action", "rewrite")
    text = params.get("block_content", "") or ""
    if action == "concise":
        new = ("（更简洁）" + text[:max(20, len(text) // 2)] + "……核心结论先行，删去冗余铺垫。") if len(text) > 40 \
            else "（更简洁）" + text
    elif action == "pro":
        new = "（更专业）" + text.replace("做了", "主导交付了").replace("很多", "显著").replace("一些", "若干")
    elif action == "quant":
        new = "（更量化）" + text.replace("提升约", "提升 18%（").replace("缩短至", "缩短 36% 至") \
              + " [补充指标：效率 +22% / 成本 -15%]"
    else:
        new = "（重新改写）" + text.replace("你", "我").replace("建议", "我建议")
    return {"content": new}


def template_chat(messages: list) -> str:
    # messages 为 OpenAI 格式；最后一条用户消息即当前问题
    last_user = ""
    for m in reversed(messages):
        if m.get("role") == "user":
            last_user = m.get("content", "")
            break
    q = (last_user or "").lower()
    job = "目标岗位"
    style = "通用平衡"
    if "面试" in q:
        return (f"针对「{job}」面试，建议从报告里挑 2 个最硬的项目经历，用 STAR 结构讲："
                "背景—你做了什么关键决策—可量化结果。报告「面试问答素材」模块已给出示范开头，"
                f"照着练 3 遍，并把语气调成你设定的「{style}」风格会更自然。")
    if "简历" in q:
        return ("简历优化上，优先复用报告「简历优化文案」里的示范条目，并补齐具体指标"
                "（转化率、效率、成本）。每条经历都写成「动作 + 数字 + 结果」最稳妥。")
    if any(k in q for k in ("转型", "转行", "职业", "方向")):
        return (f"关于向「{job}」转型：先盘点现有经历中与目标重合的能力"
                "（报告「岗位匹配度」已列出优势信号），再针对差距补 1-2 个证明项目。"
                "按 30 天微行动逐步缩小差距。")
    return (f"我已结合你的诊断报告理解你的情况，可就这些方向继续问我：\n"
            f"• 某段经历怎么改写得更专业 / 更量化；\n• 某个面试问题怎么回答更稳；\n"
            f"• 如何围绕「{job}」做能力补强与转型准备。告诉我具体场景，我给你可落地的建议。")
